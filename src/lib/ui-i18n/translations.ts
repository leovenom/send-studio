export type UiTranslationKey = keyof typeof ptBR;

export const UI_TRANSLATIONS: Record<UiLocale, Record<UiTranslationKey, string>> = {
  "pt-BR": ptBR,
  en,
};

export function getUiT(locale: UiLocale) {
  const dict = UI_TRANSLATIONS[locale];
  const fallback = UI_TRANSLATIONS["pt-BR"];

  return function t(
    key: UiTranslationKey,
    vars?: Record<string, string | number>,
  ): string {
    let text = dict[key] ?? fallback[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        text = text.replaceAll(`{{${k}}}`, String(v));
      }
    }
    return text;
  };
}
